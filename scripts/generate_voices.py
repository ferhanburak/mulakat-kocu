"""
Generates the interviewer's voice clips for every question in the catalogue.

Usage (from the project root):
    pip install edge-tts
    python scripts/generate_voices.py

- Reads question texts from src/data (build.ts and catalog/*.ts).
- Writes one MP3 per unique question to assets/voice/<hash>.mp3 (existing files are kept,
  clips of removed questions are deleted).
- Writes src/data/voiceClips.ts, mapping question text -> bundled clip.

Voices: Turkish questions use a native Turkish voice, English ones a native English voice.

Backend: if AZURE_SPEECH_KEY and AZURE_SPEECH_REGION are set, the official Azure Speech
REST API is used (use this for store releases). Otherwise the free Edge read-aloud service
(edge-tts) is used, which is fine for development.
"""

import asyncio
import hashlib
import os
import re
import sys
import urllib.request
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "assets" / "voice"
MAP_FILE = ROOT / "src" / "data" / "voiceClips.ts"
SOURCES = [ROOT / "src" / "data" / "build.ts", *sorted((ROOT / "src" / "data" / "catalog").glob("*.ts"))]

VOICES = {"tr": "tr-TR-EmelNeural", "en": "en-US-AvaMultilingualNeural"}
TURKISH_CHARS = re.compile(r"[çğıöşüÇĞİÖŞÜ]")
ENGLISH_WORDS = re.compile(r"\b(the|you|your|we|me|about|what|why|where|how|tell)\b", re.I)
Q_CALL = re.compile(r"\bq\(\s*'[a-z]+',\s*'((?:[^'\\]|\\.)*)'", re.S)


def collect() -> dict[str, str]:
    """question text -> language"""
    texts: dict[str, str] = {}
    for path in SOURCES:
        for m in Q_CALL.finditer(path.read_text(encoding="utf-8")):
            text = m.group(1).replace("\\'", "'")
            texts[text] = "en" if not TURKISH_CHARS.search(text) and ENGLISH_WORDS.search(text) else "tr"
    return texts


def clip_name(lang: str, text: str) -> str:
    return hashlib.sha1(f"{VOICES[lang]}|{text}".encode()).hexdigest()[:12] + ".mp3"


def azure(lang: str, text: str, out: Path, key: str, region: str) -> None:
    ssml = (
        f"<speak version='1.0' xml:lang='{'tr-TR' if lang == 'tr' else 'en-US'}'>"
        f"<voice name='{VOICES[lang]}'>{escape(text)}</voice></speak>"
    )
    req = urllib.request.Request(
        f"https://{region}.tts.speech.microsoft.com/cognitiveservices/v1",
        data=ssml.encode(),
        headers={
            "Ocp-Apim-Subscription-Key": key,
            "Content-Type": "application/ssml+xml",
            "X-Microsoft-OutputFormat": "audio-24khz-48kbitrate-mono-mp3",
            "User-Agent": "mulakat-kocu-voices",
        },
    )
    with urllib.request.urlopen(req) as res:
        out.write_bytes(res.read())


async def edge(lang: str, text: str, out: Path) -> None:
    import edge_tts

    await edge_tts.Communicate(text, VOICES[lang]).save(str(out))


async def main() -> None:
    texts = collect()
    if not texts:
        sys.exit("No questions found; check the q(...) pattern.")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    key, region = os.environ.get("AZURE_SPEECH_KEY"), os.environ.get("AZURE_SPEECH_REGION")
    print(f"{len(texts)} questions, backend: {'Azure' if key and region else 'edge-tts'}")

    wanted: dict[str, str] = {}
    made = 0
    for text, lang in texts.items():
        name = clip_name(lang, text)
        wanted[text] = name
        out = OUT_DIR / name
        if out.exists() and out.stat().st_size > 0:
            continue
        for attempt in range(3):
            try:
                if key and region:
                    azure(lang, text, out, key, region)
                else:
                    await edge(lang, text, out)
                break
            except Exception as e:  # network hiccups: retry, then give up on this clip
                if attempt == 2:
                    print(f"  failed: {text[:50]}… ({e})")
                    out.unlink(missing_ok=True)
                    wanted.pop(text)
        made += 1

    for f in OUT_DIR.glob("*.mp3"):
        if f.name not in wanted.values():
            f.unlink()

    lines = [
        "// Generated by scripts/generate_voices.py. Do not edit by hand.",
        "// Question text -> bundled interviewer voice clip.",
        "export const VOICE_CLIPS: Record<string, number> = {",
    ]
    for text, name in sorted(wanted.items(), key=lambda kv: kv[1]):
        js = text.replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  '{js}': require('../../assets/voice/{name}'),")
    lines.append("};\n")
    MAP_FILE.write_text("\n".join(lines), encoding="utf-8")
    size = sum(f.stat().st_size for f in OUT_DIR.glob("*.mp3")) / 1e6
    print(f"generated {made}, total {len(wanted)} clips, {size:.1f} MB")


if __name__ == "__main__":
    asyncio.run(main())
